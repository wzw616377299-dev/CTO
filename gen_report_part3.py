m2=pickle.load(open(os.path.join(BASE,'CTO','metrics2.pkl'),'rb'))
g=dict(m1); g.update(m2)
PV=g['PV']; UV=g['UV']; SESSION=g['SESSION']
out=[]
A=out.append
A('---')
A('')
A('## 六、用户满意度评估')
A('')
A('### 6.1 评估方法')
A('')
A('采用**多维情感信号加权评分法**（1-5 星制），将会话语料信号映射为满意度分值：')
A('')
A('| 信号 | 权重 | 判断关键词 / 条件 |')
A('|------|------|--------------------|')
A('| 正向情感 | +0.8 | 谢谢、感谢、明白了、好的、解决了、收到 |')
A('| 负向情感 | -1.0 | 垃圾、投诉、举报、骗、坑、乱收费、气死、恶心 |')
A('| 强烈不满（叠加）| -1.2 | 骗、坑、投诉、举报、乱收费、恶心 |')
A('| 未解决信号 | -0.8 | 没用、还是不行、答非所问、你没懂、不是这个 |')
A('| 无正向时喊人工 | -0.4 | 人工、真人、客服 |')
A('| 多轮未决（≥6 轮无正向） | -0.5 | — |')
A('| 一问一答完结（无负向） | +0.2 | — |')
A('| 基准分 | 4.0 | — |')
A('')
A('### 6.2 整体满意度')
A('')
A(f'- **平均满意度：{g["avg_sat"]:.2f} / 5.0 分**（会话级加权）')
A(f'- **正向情感会话**：{g["sent_pos"]:,}（占 {g["sent_pos"]/SESSION*100:.2f}%）')
A(f'- **负向情感会话**：{g["sent_neg"]:,}（占 {g["sent_neg"]/SESSION*100:.2f}%）')
A(f'- **强烈不满会话**：{g["sent_strong_neg"]:,}（占 {g["sent_strong_neg"]/SESSION*100:.2f}%）⚠️')
A(f'- **用户明确表达未解决**：{g["sent_unresolved"]:,}（占 {g["sent_unresolved"]/SESSION*100:.2f}%）')
A('')
A('### 6.3 满意度分布')
A('')
A('| 等级 | 会话数 | 占比 | 热力 |')
A('|------|--------|------|------|')
for k in ['非常满意(5★)','满意(4★)','一般(3★)','不满意(2★)','非常不满(1★)']:
    v=g['dist'].get(k,0); pct=v/SESSION*100; bar='█'*max(1,int(pct/2))
    A(f'| {k} | {v:,} | {pct:.2f}% | `{bar}` |')
A('')
A('### 6.4 情感倾向综合判断')
A('')
net=(g['sent_pos']-g['sent_neg'])/SESSION*100
A(f'- **净情感值（NPS 近似）** = 正向 {g["sent_pos"]/SESSION*100:.2f}% − 负向 {g["sent_neg"]/SESSION*100:.2f}% = **{net:+.2f}%**')
if net > 10: verdict = '整体情感健康，AI 应答获得较好用户接受度'
elif net > 0: verdict = '略偏正向，但存在改进空间，负向案例需专项治理'
else: verdict = '情感偏负向，建议加大人工介入和复盘力度'
A(f'- **结论**：{verdict}。')
A(f'- **风险提示**：强烈不满会话 {g["sent_strong_neg"]:,} 个（{g["sent_strong_neg"]/SESSION*100:.2f}%），涉及"欺诈/乱收费/投诉"等关键词，单个事件即可能引发舆情风险，建议接入实时监控告警。')
A('')
A('### 6.5 典型会话判定示例')
A('')
A('**✅ 正向满意（AI 自动应答成功解决）**')
A('> 用户：`可以把会员分享给好友吗 如何操作`  ')
A('> AI：`可以哦～腾讯视频会员能通过礼品卡分享给好友。你可前往[腾讯视频礼品卡]页面...`  ')
A('> **判定**：意图明确、AI 给出可执行路径、未触发负向信号 → **4★**')
A('')
A('**⚠️ 负向不满（退款诉求遭拒）**')
A('> 用户：`svip 充成 vip 了怎么退`  ')
A('> AI：`...因为是即时到账的虚拟服务，所以暂时没办法退费哦...`  ')
A('> **判定**：用户诉求被拒绝、若后续无追加正向表达 → **2★**  ')
A('> **建议**：此类场景增加"协商换购 SVIP 补差价"的挽留方案。')
A('')
A('**❌ 强烈不满（首轮喊人工 + 负向情绪）**')
A('> 用户：`我要人工！！垃圾！`  ')
A('> **判定**：强烈负向 + 未解决 → **1★**，应立即触发人工优先接入。')
A('')
A('**🔄 未解决重复提问**')
A('> 用户首轮：`退款`  AI：`...暂时没法申请退款。不过自动续费已关闭...`  ')
A('> 用户次轮：`还是不行`  ')
A('> **判定**：未解决信号命中 → **2★ 起评**，进入人工升级队列。')
A('')
